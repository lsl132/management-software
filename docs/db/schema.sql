-- ============================================================================
-- backend-management 数据库结构（PostgreSQL 16）
-- 与 com.gangtise.backend.domain.aggregate / com.gangtise.backend.domain.aggregate.entity
-- 下的 15 个实体一一对应，表名 = 类名下划线风格，列名 = 属性名下划线风格
--
-- 执行方式（幂等，可重复执行）：
--   psql -h localhost -p 5432 -U postgres -d backend_management -f docs/db/schema.sql
--
-- 约定：
--   1. 主键统一为 identity 自增列，Java 侧使用 @TableId(type = IdType.AUTO)
--   2. 审计字段 create_time / update_time 为 timestamp（无时区，对应 LocalDateTime），
--      由 MyMetaObjectHandler 自动填充，同时保留数据库默认值兜底
--   3. 不使用外键约束，关联列只建普通索引，便于后续服务拆分与数据迁移
--   4. 金额类字段统一 numeric(18,2)，考勤时长/天数统一 numeric(10,2)，Java 侧映射为 Double
--   5. "user" 是 PostgreSQL 保留字，建表与查询必须加双引号（实体侧 @TableName("\"user\"")）
-- ============================================================================

begin;

-- ============================================================================
-- 1. department 部门
-- ============================================================================
create table if not exists department (
    id          integer     generated by default as identity primary key,
    parent_id   integer,
    depart_name varchar(64)  not null,
    description varchar(255),
    create_time timestamp    not null default current_timestamp
);
comment on table department is '部门';
comment on column department.id is '自增ID';
comment on column department.parent_id is '上级部门ID，顶级部门为 null';
comment on column department.depart_name is '部门名称';
comment on column department.description is '部门简介';
comment on column department.create_time is '创建时间';
create index if not exists idx_department_parent_id on department (parent_id);
-- 部门名称唯一（字典 seed 脚本依赖该唯一键做幂等 upsert）
create unique index if not exists uk_department_depart_name on department (depart_name);

-- ============================================================================
-- 2. employee 员工
-- ============================================================================
create table if not exists employee (
    id            integer      generated by default as identity primary key,
    work_no       varchar(32)  not null,
    name          varchar(64)  not null,
    alias         varchar(64),
    gender        smallint,
    identity_card varchar(32),
    telephone     varchar(32),
    email         varchar(128),
    address       varchar(255),
    status        smallint     not null default 0,
    birthday      integer,
    education     smallint,
    rank          smallint,
    department    integer,
    update_time   timestamp    not null default current_timestamp,
    create_time   timestamp    not null default current_timestamp
);
-- 可选字段允许为 null：表单里「未选择」即写 null，避免用 0（会与枚举有效值混淆）
alter table employee alter column gender drop not null;
alter table employee alter column gender drop default;
alter table employee alter column education drop not null;
alter table employee alter column education drop default;
alter table employee alter column rank drop not null;
alter table employee alter column rank drop default;
comment on table employee is '员工';
comment on column employee.id is '自增id';
comment on column employee.work_no is '员工工号';
comment on column employee.name is '员工名称';
comment on column employee.alias is '别名';
comment on column employee.gender is '性别 1 男 2 女，未填写为 null';
comment on column employee.identity_card is '身份证号';
comment on column employee.telephone is '电话号码';
comment on column employee.email is '电子邮箱';
comment on column employee.address is '居住地址';
comment on column employee.status is '状态 见 EmployeeStatusEnum';
comment on column employee.birthday is '生日 yyyyMMdd';
comment on column employee.education is '学历 见 EmployeeEducationEnum，未填写为 null';
comment on column employee."rank" is '职级，关联 department_rank.id，必须与 department 一致（职级隶属于部门），未填写为 null';
comment on column employee.department is '所属部门ID，关联 department.id；填写职级时必须同时填写';
comment on column employee.update_time is '更新时间';
comment on column employee.create_time is '创建时间';
-- 工号唯一（业务键）：应用层先查重给出友好提示，此处为最终兜底，禁止重复工号
create unique index if not exists uk_employee_work_no on employee (work_no);
create index if not exists idx_employee_department on employee (department);
create index if not exists idx_employee_status on employee (status);

-- ============================================================================
-- 3. department_rank 部门职级（职级隶属于部门）
-- ============================================================================
-- 已有库升级：旧表 employee_rank 改名为 department_rank（幂等，仅当旧表在、新表不在时执行）
do $$
begin
    if to_regclass('employee_rank') is not null and to_regclass('department_rank') is null then
        alter table employee_rank rename to department_rank;
        alter index if exists employee_rank_pkey rename to department_rank_pkey;
        alter index if exists uk_employee_rank_code rename to uk_department_rank_code;
        alter index if exists idx_employee_rank_department rename to idx_department_rank_department;
        raise notice '已迁移表 employee_rank -> department_rank';
    end if;
end $$;
-- 历史库兜底：表已改名但主键索引仍为旧名时补齐（幂等，无旧索引时不报错）
alter index if exists employee_rank_pkey rename to department_rank_pkey;

create table if not exists department_rank (
    id          integer     generated by default as identity primary key,
    code        varchar(32) not null,
    type        smallint    not null default 0,
    department  integer     not null,
    intro       varchar(255),
    create_time timestamp   not null default current_timestamp
);
-- 已有库升级：补出 department 列（此列由 seed 脚本回填归属部门后收紧为 not null）
alter table department_rank add column if not exists department integer;
comment on table department_rank is '部门职级（职级隶属于部门，不同部门有各自的职级）';
comment on column department_rank.id is '自增id';
comment on column department_rank.code is '职级编码，全公司唯一';
comment on column department_rank.type is '职级类型（序列），见 RankTypeEnum';
comment on column department_rank.department is '归属部门，关联 department.id（department 为 null 时先执行 seed 脚本回填）';
comment on column department_rank.intro is '职级说明';
comment on column department_rank.create_time is '创建时间';
create unique index if not exists uk_department_rank_code on department_rank (code);
create index if not exists idx_department_rank_department on department_rank (department);

