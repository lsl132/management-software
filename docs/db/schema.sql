-- ============================================================================
-- 6. attendance 考勤统计（按人按天汇总）
-- ============================================================================
create table if not exists attendance (
    id          bigint        generated by default as identity primary key,
    work_no     varchar(32)   not null,
    day         integer       not null,
    first       bigint,
    last        bigint,
    extra       numeric(10,2) not null default 0,
    status      smallint      not null default 0,
    create_time timestamp     not null default current_timestamp
);
comment on table attendance is '考勤统计';
comment on column attendance.id is '自增id';
comment on column attendance.work_no is '员工工号';
comment on column attendance.day is '日期 yyyyMMdd';
comment on column attendance.first is '最早打卡时间（epoch 毫秒）';
comment on column attendance."last" is '最晚打卡时间（epoch 毫秒）';
comment on column attendance.extra is '加班时间（小时）';
comment on column attendance.status is '状态';
comment on column attendance.create_time is '创建时间';
-- 业务键是「人 + 天」：唯一索引既是查重兜底，也是 on conflict (work_no, day) do update 的冲突键，
-- 让考勤统计定时任务重跑（多实例同时触发 / 人工补算 / 改完上下班时间重算）保持幂等
create unique index if not exists uk_attendance_work_no_day on attendance (work_no, day);
-- 原 (work_no, day) 普通索引升级为唯一索引后已冗余（唯一索引同样能支撑该前缀的查询），
-- 多余索引只会拖慢写入，这里一并移除。放在建唯一索引之后执行：若唯一索引因历史重复数据建不出来，
-- 至少普通索引还在，不会两头落空
drop index if exists idx_attendance_work_no_day;

