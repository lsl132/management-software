-- 必须排在下面那些 comment on column 之前，否则列还不存在，注释语句会把整个脚本打断
alter table employee_salary add column if not exists update_time timestamp not null default current_timestamp;
alter table employee_salary add column if not exists update_by varchar(64);
comment on column employee_salary.id is '自增id';
comment on column employee_salary.work_no is '员工工号';
comment on column employee_salary.currency is '币种 见 CurrencyEnum';
