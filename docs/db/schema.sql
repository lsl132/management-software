-- 一人一行：业务键是工号，靠唯一索引兜底，同时作为 upsert 的冲突键（原普通索引冗余已移除）
create unique index if not exists uk_employee_salary_work_no on employee_salary (work_no);
drop index if exists idx_employee_salary_work_no;

